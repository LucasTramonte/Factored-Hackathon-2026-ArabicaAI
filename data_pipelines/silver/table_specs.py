# --------------------------------------------------------------------------------------
# transactions -- currency conversion via the EXACT-DATE rate (a transaction has a real date to
# join against), with a fallback that fills the gap Bronze itself leaves: amount_usd is null for
# 57.34% of rows (confirmed in the Bronze profile), computed here as amount * that day's rate
# whenever the source amount_usd is missing. amount_usd_is_estimated flags which rows are
# Silver-derived vs. genuinely sourced, so downstream analysis can decide whether to trust,
# exclude, or separately caveat the estimated ones.
# --------------------------------------------------------------------------------------
transactions_spec = TableSpec(
    name="transactions",
    kind="fact",
    source_alias="t",
    extra_joins=[
        "LEFT JOIN silver.dim_fx_rates fx "
        "ON fx.source_currency = trim(t.currency) "
        "AND fx.target_currency = 'USD' "
        "AND fx.rate_date = TRY_CAST(t.transaction_date AS DATE)",
    ],
    primary_key=["transaction_id"],
    dedup_order_by="t._ingested_at DESC",
    columns=[
        ColumnSpec("t.transaction_id"),
        ColumnSpec("t.transaction_date", transform="timestamp"),
        ColumnSpec("t.process_date", transform="date"),
        ColumnSpec("t.product_id"),
        ColumnSpec("t.customer_id"),
        ColumnSpec("t.transaction_type"),
        ColumnSpec("t.transaction_category"),
        ColumnSpec("t.amount", transform="double"),
        ColumnSpec("t.currency"),
        ColumnSpec(
            source="t.amount_usd", target="amount_usd",
            expr=(
                "COALESCE(TRY_CAST(t.amount_usd AS DOUBLE), "
                "TRY_CAST(t.amount AS DOUBLE) * fx.exchange_rate)"
            ),
        ),
        ColumnSpec(
            source="t.amount_usd", target="amount_usd_is_estimated",
            expr=(
                "(TRY_CAST(t.amount_usd AS DOUBLE) IS NULL "
                "AND TRY_CAST(t.amount AS DOUBLE) * fx.exchange_rate IS NOT NULL)"
            ),
        ),
        ColumnSpec("t.channel"),
        ColumnSpec("t.branch_id"),
        ColumnSpec("t.merchant_name"),
        ColumnSpec("t.merchant_category"),
        ColumnSpec("t.transaction_country", target="transaction_country", transform="country"),
        ColumnSpec("t.transaction_city"),
        ColumnSpec("t.transaction_status"),
        ColumnSpec("t.response_code"),
        ColumnSpec("t.is_fraud", transform="boolean"),
        ColumnSpec("t.fraud_score", transform="double"),
        ColumnSpec("t.latitude", transform="double"),
        ColumnSpec("t.longitude", transform="double"),
    ],
)

