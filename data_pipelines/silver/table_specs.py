"""
Declarative Silver table specs -- one TableSpec per table, built from the real Bronze profile
(bronze_profile.md, generated by profile_bronze.py) rather than the data dictionary, which this
project has already found wrong three separate times before this pipeline even existed.

All 13 Bronze tables are specced here:
  - customers, branches, service_agents, marketing_campaigns: plain dimensions --
    string/numeric/date typing, country canonicalization.
  - products: dimension + currency conversion via the LATEST available FX rate (no natural "as of"
    date on a snapshot row).
  - transactions: fact + currency conversion via the EXACT-DATE FX rate, plus a fallback that
    fills the 57.34% of amount_usd that Bronze itself leaves null, using amount * that day's rate.
  - campaign_sends: fact + the literal "nan"-in-subject text bug fix.
  - call_center_interactions, call_transcripts, satisfaction_surveys, complaints, digital_events:
    facts, same typing/sentinel/country patterns as above; table-specific notes are next to each
    spec below (contact_reason/reason_category apparent duplication, origin_interaction_id drop,
    digital_events' size).

Every fact table drops the Hive partition columns (day, month, year) from its Silver output --
they're a Bronze/S3 storage artifact (DuckDB infers `year` as BIGINT, `month`/`day` stay VARCHAR
with leading zeros -- see profile_bronze.py's findings), not source data, and each table already
carries a real business timestamp/date column that supersedes them.

Naming convention: every table's `kind` ("dimension" or "fact") determines its silver.* prefix --
`silver.customers` is actually created as `silver.dim_customers`, `silver.transactions` as
`silver.fact_transactions`, and so on (TableSpec.silver_table_name() in silver.py does the
prefixing). `name` here stays UNPREFIXED throughout this file and matches the unprefixed
bronze.<name> source table and the --tables CLI filter -- only the actual CREATE TABLE target gets
prefixed. customers, branches, products, service_agents, marketing_campaigns (and the FX table,
dim_fx_rates) are dimensions; transactions, campaign_sends, call_center_interactions,
call_transcripts, satisfaction_surveys, complaints, digital_events are facts.
"""
